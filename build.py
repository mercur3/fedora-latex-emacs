#!/usr/bin/python3
from pathlib import Path

SUPPORTED_FEDORA_VERSIONS: list[int] = [44, 45]
LATEX_CONFIG = ["base", "medium", "full"]
PUSHED_LATEX_CONFIG = ["medium", "full"]
BASE_BUILD_DIR = "build"

REPOSITORY = "mercur3/fedora-latex-emacs"
GHCR_REPOSITORY = "ghcr.io/mercur3/fedora-latex-emacs"

OUTPUT_FILE = Path(".github/workflows/build.yml")


def generate_dockerfiles(version: int, tag_base: str, tag_medium: str, tag_full: str) -> None:
    with open(f"{BASE_BUILD_DIR}/Dockerfile.{version}-base", "w") as fd:
        content = f"""
FROM fedora:{version}

###############################################################################
# WARNING                                                                     #
# This file is autogenerated. Do NOT edit this file. Run =./build.py= instead #
###############################################################################

# By default dnf is configured as a singletheaded application. This configuration aims to increase
# build speed as it spends less time doing I/O operations and connecting to the mirrors.
RUN rm /etc/dnf/dnf.conf
COPY dnf.conf /etc/dnf/
RUN set -eux && \\
    dnf update  --nodocs && \\
    dnf install --nodocs emacs-nox texlive-scheme-medium && \\
    dnf install          "tex(datetime.sty)";

"""
        fd.write(content)

    with open(f"{BASE_BUILD_DIR}/Dockerfile.{version}-medium", "w") as fd:
        content = f"""
FROM {tag_base}

###############################################################################
# WARNING                                                                     #
# This file is autogenerated. Do NOT edit this file. Run =./build.py= instead #
###############################################################################

LABEL description="Fedora + texlive-medium + Emacs. Can be used to build LaTeX documents with org-mode"
LABEL repository="https://gitlab.com/mercur3-dockerfiles/fedora-latex-emacs.git"
LABEL readme="README.org"

RUN dnf clean all

"""
        fd.write(content)

    with open(f"{BASE_BUILD_DIR}/Dockerfile.{version}-full", "w") as fd:
        content = f"""
FROM {tag_base}

###############################################################################
# WARNING                                                                     #
# This file is autogenerated. Do NOT edit this file. Run =./build.py= instead #
###############################################################################

LABEL description="Fedora + texlive-full + Emacs. Can be used to build LaTeX documents with org-mode"
LABEL repository="https://gitlab.com/mercur3-dockerfiles/fedora-latex-emacs.git"
LABEL readme="README.org"

RUN dnf install --nodocs texlive-scheme-full && \\
    dnf clean all;

"""
        fd.write(content)


HEADER = """\
###############################################################################
# WARNING                                                                     #
# This file is autogenerated. Do NOT edit this file. Run =./build.py= instead #
###############################################################################

name: Build & Push Fedora LaTeX Emacs

on:
  push:
    branches:
      - master
  pull_request:
    branches:
      - master

# Cancel superseded runs of the same PR (equivalent of Azure's `autoCancel`)
concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: ${{ github.event_name == 'pull_request' }}

permissions:
  contents: read
  packages: write  # lets GITHUB_TOKEN push to ghcr.io

jobs:
  build:
    name: Building on Fedora ${{ matrix.fedora_version }}
    runs-on: ubuntu-latest
    strategy:
      fail-fast: false
      matrix:
        fedora_version: __FEDORA_VERSIONS__
    env:
      FEDORA_VERSION: ${{ matrix.fedora_version }}
      REPOSITORY: __REPOSITORY__
      GHCR_REPOSITORY: __GHCR_REPOSITORY__
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: System info
        run: |
          echo "Building the images on Fedora $FEDORA_VERSION"
          echo "Using $(nproc) threads"
"""

BUILD_STEP = """
      - name: Build __CONFIG__
        working-directory: __BUILD_DIR__
        run: |
          docker build -f Dockerfile.$FEDORA_VERSION-__CONFIG__ \\
                       -t $REPOSITORY:$FEDORA_VERSION-__CONFIG__ .
"""

FOOTER = """
      # Token based authentication: a Docker Hub access token (not the account password)
      - name: Log in to Docker Hub
        if: github.event_name != 'pull_request'
        uses: docker/login-action@v3
        with:
          username: ${{ secrets.DOCKERHUB_USERNAME }}
          password: ${{ secrets.DOCKERHUB_TOKEN }}

      # Token based authentication: the built-in GITHUB_TOKEN
      - name: Log in to GitHub Container Registry
        if: github.event_name != 'pull_request'
        uses: docker/login-action@v3
        with:
          registry: ghcr.io
          username: ${{ github.actor }}
          password: ${{ secrets.GITHUB_TOKEN }}

      # Every image is pushed to both registries at the same time
      - name: Push images
        if: github.event_name != 'pull_request'
        env:
          CONFIGS: "__PUSHED_CONFIGS__"
        run: |
          pids=()
          for config in $CONFIGS; do
            hub="$REPOSITORY:$FEDORA_VERSION-$config"
            ghcr="$GHCR_REPOSITORY:$FEDORA_VERSION-$config"
            docker tag "$hub" "$ghcr"
            docker push "$hub" & pids+=($!)
            docker push "$ghcr" & pids+=($!)
          done
          status=0
          for pid in "${pids[@]}"; do
            wait "$pid" || status=1
          done
          exit "$status"
"""


def main() -> None:
    Path(BASE_BUILD_DIR).mkdir(exist_ok=True)
    for f in SUPPORTED_FEDORA_VERSIONS:
        # build =Dockerfile.<version>-<config>=
        tag_base = f"{REPOSITORY}:{f}-base"
        tag_medium = f"{REPOSITORY}:{f}-medium"
        tag_full = f"{REPOSITORY}:{f}-full"
        generate_dockerfiles(f, tag_base, tag_medium, tag_full)

    # build =.github/workflows/build.yml=
    output = (
        HEADER.replace("__FEDORA_VERSIONS__", str([str(f) for f in SUPPORTED_FEDORA_VERSIONS]))
        .replace("__REPOSITORY__", REPOSITORY)
        .replace("__GHCR_REPOSITORY__", GHCR_REPOSITORY)
    )
    for config in LATEX_CONFIG:
        output += BUILD_STEP.replace("__CONFIG__", config).replace("__BUILD_DIR__", BASE_BUILD_DIR)
    output += FOOTER.replace("__PUSHED_CONFIGS__", " ".join(PUSHED_LATEX_CONFIG))

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(output)


if __name__ == "__main__":
    main()

